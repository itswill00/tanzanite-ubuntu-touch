#!/usr/bin/env bash
# Regenerates overlay/system/usr/lib/modules-load.d/tanzanite.conf from the .ko
# files that are actually shipped, so systemd-modules-load stops asking for
# modules that do not exist.
#
# Every entry in that file without a matching .ko makes systemd log
# "Failed to find module" at boot. On this tree that was 150 of 174 entries.
#
# Modules that Halium already loads from vendor_boot (i.e. everything listed in
# modules.load) are intentionally NOT repeated here: loading them twice is
# harmless but noisy, and Halium's loader is the authoritative one for drivers
# needed before the rootfs is up.
#
# This file therefore only covers modules that must be loaded *after* the
# rootfs is mounted, which is a much smaller set. Add modules to EXTRA below if
# you find one that needs userspace-triggered loading.
#
# Usage:
#   ./scripts/sync_modules_load_conf.sh            # rewrite the conf
#   ./scripts/sync_modules_load_conf.sh --check    # exit 1 if it would change
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODDIR="$ROOT/vendor-ramdisk-overlay/lib/modules"
OUT="$ROOT/overlay/system/usr/lib/modules-load.d/tanzanite.conf"
CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

[ -d "$MODDIR" ] || { echo "missing $MODDIR" >&2; exit 1; }

# Modules that must be loaded by systemd rather than by the Halium vendor
# ramdisk loader. Keep this list short and justified per entry.
EXTRA=(
    # zram swap is configured by the rootfs, after /data is mounted
    zram
    zsmalloc
)

cd "$MODDIR"
shopt -s nullglob
declare -A HAVE=()
for f in *.ko; do HAVE["${f%.ko}"]=1; done

TMP="$(mktemp)"
{
    echo "# Generated by scripts/sync_modules_load_conf.sh - do not edit by hand."
    echo "#"
    echo "# Only modules that must be loaded after the rootfs is up. Everything else"
    echo "# is loaded by Halium from vendor_boot via lib/modules/modules.load."
    echo "# Entries here are validated against the .ko files shipped in"
    echo "# vendor-ramdisk-overlay/lib/modules/; anything without a file is omitted"
    echo "# so systemd-modules-load does not log failures at boot."
    echo
    kept=0
    for m in "${EXTRA[@]}"; do
        if [ -n "${HAVE[$m]:-}" ]; then
            echo "$m"
            kept=$((kept+1))
        else
            echo "# skipped (no .ko shipped): $m"
        fi
    done
} > "$TMP"

TOTAL=$(grep -vcE '^\s*#|^\s*$' "$TMP")
echo "generated $TOTAL entry(ies) from a list of ${#EXTRA[@]}"

if [ "$CHECK" -eq 1 ]; then
    if diff -q "$OUT" "$TMP" >/dev/null 2>&1; then
        echo "tanzanite.conf is up to date"; rm -f "$TMP"; exit 0
    else
        echo "tanzanite.conf is OUT OF DATE - run ./scripts/sync_modules_load_conf.sh" >&2
        diff -u "$OUT" "$TMP" >&2 || true
        rm -f "$TMP"; exit 1
    fi
fi

mv "$TMP" "$OUT"
echo "wrote $OUT"
