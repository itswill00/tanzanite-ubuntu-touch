#!/usr/bin/env bash
# Regenerates vendor-ramdisk-overlay/lib/modules/modules.load from the .ko files
# that are actually shipped, so the load list can never drift from the file set.
#
# Halium reads modules.load inside vendor_boot and loads exactly what it names.
# A module present on disk but absent from modules.load is never loaded; a name
# in modules.load without a file makes the loader log an error and continue.
#
# Module order matters: a driver must be loaded after its dependencies. The
# ordering below encodes the dependency classes observed on MT6789 (clocks and
# pinctrl first, then buses, then storage/display/audio, then leaf drivers).
#
# Usage:
#   ./scripts/sync_modules_load.sh            # rewrite modules.load
#   ./scripts/sync_modules_load.sh --check    # exit 1 if it would change
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODDIR="$ROOT/vendor-ramdisk-overlay/lib/modules"
OUT="$MODDIR/modules.load"
CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

[ -d "$MODDIR" ] || { echo "missing $MODDIR" >&2; exit 1; }

cd "$MODDIR"
shopt -s nullglob
ALL=( *.ko )
[ ${#ALL[@]} -gt 0 ] || { echo "no .ko files in $MODDIR" >&2; exit 1; }

# Strip .ko and index the full set.
declare -A HAVE=()
for f in "${ALL[@]}"; do HAVE["${f%.ko}"]=1; done

# Load order, grouped by dependency class. Anything not listed here is appended
# afterwards in alphabetical order, so new modules are never silently dropped.
GROUPS=(
  # --- platform plumbing: clocks, pinctrl, power domains ---
  "clk-mt6789 clk-common clk-bringup clk-chk-mt6789 clk-mt6789-audiosys
   clk-mt6789-bus clk-mt6789-cam clk-mt6789-disp_dsc clk-mt6789-i2c
   clk-mt6789-img clk-mt6789-impen clk-mt6789-mfgcfg clk-mt6789-mmsys
   clk-mt6789-vcodec pinctrl-mtk-v2 pinctrl-mt6789 pinctrl-mtk-common-v2_debug
   mtk-pm-domain-disable-unused mtk-power-controller spmi-mtk-pmif"

  # --- debug / crash plumbing used by the drivers below ---
  "bootprof mrdump aee_aed aee_hangdet monitor_hang mtk_printk_ctrl log_store
   dbgtop-drm mtk_disp_notify hq_notify mkp"

  # --- mailbox / ipi / cmdq ---
  "mtk-mbox mtk_rpmsg_mbox mtk_tinysys_ipi mtk-cqdma cmdq-platform-mt6789
   cmdq_helper_inf"

  # --- storage ---
  "ufs-mediatek-mod ufs-mediatek ufs_mediatek cqhci"

  # --- display ---
  "mediatek-drm mtk_drm mtk-drm mtk_disp_sec pwm-mtk-disp leds-mtk-disp
   mtk_disp_ccorr mtk_disp_color mtk_disp_gamma mtk_disp_ovl mtk_disp_rdma"

  # --- leds / backlight / torch ---
  "leds-mtk leds-mtk-pwm mtk-pwm mtk_irtx_pwm flashlight flashlights-mt6789-o7
   backlight_cooling"

  # --- haptics ---
  "regulator-vibrator"

  # --- audio: DSP transport, then AFE, then codec, then amps ---
  "audio_ipi adsp snd-soc-audiodsp-common mtk-scp-audiocommon mtk-scp-audio
   snd-soc-mtk-common snd-soc-mt6789-afe mt6789-mt6366 snd-soc-mt6366
   mtk-afe-external mtk-btcvsd mtk-sp-spk-amp
   snd-soc-rt5512 snd-soc-sipa snd-soc-sipa-tuning snd-soc-aw87xx snd-soc-tfa98xx
   richtek_spm_cls mt6358-accdet"

  # --- camera: ISP pipeline, then sensors, then autofocus ---
  "camera_mem camera_isp camera_dip_isp6s camera_rsc_isp60 camera_fdvt_isp51
   camera_eeprom cam_qos imgsensor_isp6s
   mainaf main2af main3af subaf sub2af mtk-composite
   mtk_cm_ipi mtk_cm_mgr mtk_cm_mgr_mt6789"

  # --- video codec ---
  "mtk-vcodec-common mtk-vcodec-dec-v1 mtk-vcodec-enc-v1 vdec-fmt mtk-vcu
   mtk_jpeg"

  # --- sensors ---
  "sensorhub hf_manager"

  # --- connectivity ---
  "btif_drv connadp cfg80211"

  # --- thermal / battery ---
  "soc_temp_lvts pmic_temp board_temp thermal-generic-adc thermal_trace
   thermal_interface md_cooling_all mtk_thermal"

  # --- misc leaf drivers ---
  "simtray reboot-mode syscon-reboot-mode zram zsmalloc"
)

TMP="$(mktemp)"
{
    echo "# Generated by scripts/sync_modules_load.sh - do not edit by hand."
    echo "# Contains every .ko shipped in this directory, ordered by dependency class."
    echo "# Regenerate after adding or removing modules."
    echo
    for group in "${GROUPS[@]}"; do
        for m in $group; do
            if [ -n "${HAVE[$m]:-}" ]; then
                echo "$m.ko"
                unset 'HAVE[$m]'
            fi
        done
    done
    # Anything left over, alphabetically, so nothing is dropped.
    if [ ${#HAVE[@]} -gt 0 ]; then
        echo
        echo "# modules not covered by the ordering table above"
        for m in $(printf '%s\n' "${!HAVE[@]}" | sort); do
            echo "$m.ko"
        done
    fi
} > "$TMP"

TOTAL=$(grep -vcE '^\s*#|^\s*$' "$TMP")
echo "generated $TOTAL module entries from ${#ALL[@]} .ko files"

if [ "$CHECK" -eq 1 ]; then
    if diff -q "$OUT" "$TMP" >/dev/null 2>&1; then
        echo "modules.load is up to date"
        rm -f "$TMP"
        exit 0
    else
        echo "modules.load is OUT OF DATE - run ./scripts/sync_modules_load.sh" >&2
        diff -u "$OUT" "$TMP" | head -40 >&2 || true
        rm -f "$TMP"
        exit 1
    fi
fi

mv "$TMP" "$OUT"
echo "wrote $OUT"
